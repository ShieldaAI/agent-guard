#!/usr/bin/env node
// Generates docs/rules.md from the rule definitions and the labeled benchmark cases, so the
// catalog never drifts from the code. `node scripts/rules-doc.mjs --write` updates the file;
// the test suite fails when it is out of date.
import { writeFileSync } from 'node:fs';
import { RULES } from '@shieldaai/agent-guard-check';
import { CASES } from '../bench/cases.mjs';

const GROUPS = [
  ['PERM', 'Permissions'],
  ['TRI', 'Lethal trifecta'],
  ['SUP', 'Supply chain'],
  ['PER', 'Persistence'],
  ['SEC', 'Secrets'],
  ['TXT', 'Instructions'],
  ['TRG', 'Triggers'],
  ['LIM', 'Limits'],
  ['IDN', 'Identity'],
  ['GOV', 'Governance'],
  ['COV', 'Runtime coverage'],
  ['POL', 'Policy as code (runs only with a policy section in .agc.yaml)'],
  ['AGX', 'Agent Guard records (runs only when describe() output, an inventory or a manifest is found)'],
  ['DRF', 'Live Agent Map (runs only with --live or --agent-map-url)'],
];
const EVIDENCE = { files: 'repository files', 'agent-guard': 'Agent Guard records', 'agent-map': 'live Agent Map' };

function example(item) {
  if (item.live) return '_Live evidence from Agent Map; no repository file._';
  const lines = [];
  if (item.config) lines.push('`.agc.yaml`:', '', '```yaml', item.config.trimEnd(), '```', '');
  for (const [path, text] of Object.entries(item.files ?? {})) {
    if (path === 'CODEOWNERS') continue;
    // Show invisible characters as escapes, so the catalog itself carries none.
    const visible = text.replace(
      /[\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufeff]/g,
      ch => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`,
    );
    // Long lines (a padded file) are cut, so an example stays readable.
    const body = visible.split('\n').map(line => (line.length > 120 ? `${line.slice(0, 120)}…` : line));
    const shown = body.length > 16 ? [...body.slice(0, 16), '…'] : body;
    const fence = path.endsWith('.json')
      ? 'json'
      : /\.ya?ml$/.test(path)
        ? 'yaml'
        : path.endsWith('.toml')
          ? 'toml'
          : '';
    lines.push(`\`${path}\`:`, '', `\`\`\`${fence}`, shown.join('\n').trimEnd(), '```', '');
  }
  return lines.join('\n').trimEnd();
}

export function rulesDoc() {
  const out = [
    '# Agent Guard Check rules',
    '',
    '<!-- Generated by scripts/rules-doc.mjs from the rule definitions and bench/cases.mjs. Do not edit by hand. -->',
    '',
    `${RULES.length} rules. Severity is the default; \`severity\` in \`.agc.yaml\` changes it. Some rules raise or lower`,
    'severity with context, and the finding message says why. Low-confidence rules match text: they are reported but',
    'never fail a run unless `--min-confidence low` is set.',
    '',
    'Each rule shows one configuration it flags and one look-alike it does not, taken from the labeled',
    'benchmark that the test suite runs.',
    '',
    '| ID | Severity | Evidence | Title |',
    '| --- | --- | --- | --- |',
    ...RULES.map(
      rule => `| [${rule.id}](#${rule.id.toLowerCase()}) | ${rule.severity} | ${EVIDENCE[rule.mode]} | ${rule.title} |`,
    ),
    '',
  ];
  for (const [prefix, title] of GROUPS) {
    const rules = RULES.filter(rule => rule.id.startsWith(`AGC-${prefix}-`));
    if (!rules.length) continue;
    out.push(`## ${title}`, '');
    for (const rule of rules) {
      const positive = CASES.find(item => item.rule === rule.id && item.expect);
      const negative = CASES.find(item => item.rule === rule.id && !item.expect);
      out.push(`### ${rule.id}`, '', `**${rule.title}**`, '');
      out.push(
        `Severity: ${rule.severity}. Confidence: ${rule.confidence}. Evidence: ${EVIDENCE[rule.mode]}. OWASP Agentic Top 10: ${rule.owasp.join(', ')}.`,
        '',
        rule.help,
        '',
      );
      if (positive) out.push('Flagged:', '', example(positive), '');
      if (negative) out.push('Not flagged:', '', example(negative), '');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

if (process.argv.includes('--write')) {
  writeFileSync(new URL('../docs/rules.md', import.meta.url), rulesDoc());
  process.stdout.write('Wrote docs/rules.md\n');
}
